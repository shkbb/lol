"""Мова відповідей: лише українська. Розшифровка пар буває російською чи суржиком, і маленька мовна модель тоді
сама переходить на російську («Тебе кличут, чтобы подтвердить…») — такого студент отримувати не має."""

from __future__ import annotations

import re

UKRAINIAN_ONLY = "Пиши лише українською мовою — навіть якщо на парі чи в питанні говорили російською."
RETRY_UKRAINIAN = "Попередня відповідь вийшла російською. Перепиши її українською мовою, нічого не додаючи."
# Літер «ы», «э», «ъ», «ё» в українській немає; плюс найчастіші російські слова, яких немає в українській.
RUSSIAN_LETTERS = re.compile(r"[ыэъё]", re.I)
RUSSIAN_WORDS = re.compile(
    r"(?<!\w)(что|чтобы|это|этот|как|кто|когда|тебя|ты|если|или|только|очень|нужно|сейчас|говорит|"
    r"называет|подтвердить|участвует|сегодня|вчера|пожалуйста|спасибо|здесь|потому|можно)(?!\w)", re.I)


def looks_russian(text: str) -> bool:
    """Чи текст (відповідь мовної моделі) російською. Цитати з пари сюди не передавати — там буває що завгодно."""
    return len(RUSSIAN_LETTERS.findall(text)) + len(RUSSIAN_WORDS.findall(text)) >= 2


def ukrainian(ask, system: str, text: str) -> str | None:
    """Відповідь мовної моделі лише українською: російською — ще одна спроба з проханням переписати;
    знову російською — None (краще промовчати, ніж надіслати таке)."""
    reply = ask(system, text)
    if not looks_russian(reply):
        return reply
    again = ask(system, f"{text}\n\n{RETRY_UKRAINIAN}\nПопередня відповідь: {reply}")
    return None if looks_russian(again) else again
